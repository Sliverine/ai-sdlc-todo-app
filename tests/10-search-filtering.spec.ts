import { expect, test, type Page } from '@playwright/test'
import { addSubtask, createTag, createTodo, register } from './helpers'
import { toSingaporeDateTimeInput } from '@/lib/timezone'

async function seed(page: Page) {
  const cdp = await register(page)
  await expect(page.getByRole('button', { name: 'Add todo', exact: true })).toBeEnabled()
  await createTag(page, 'Work')
  await page.getByLabel('Priority', { exact: true }).selectOption('high')
  await page.getByRole('button', { name: 'Work', exact: true }).click()
  const meeting = await createTodo(page, 'Team meeting')
  await expect(page.locator('.todo-title', { hasText: 'Team meeting' })).toBeVisible()
  await page.getByLabel('Priority', { exact: true }).selectOption('low')
  await createTodo(page, 'Shopping')
  await addSubtask(page, 'Shopping', 'Buy milk')
  const row = page.locator('.todo-row').filter({ hasText: 'Shopping' })
  await row.getByRole('checkbox', { name: 'Mark Shopping complete', exact: true }).check()
  await expect(row.getByRole('checkbox', { name: 'Mark Shopping incomplete', exact: true })).toBeEnabled()
  return { cdp, meeting }
}

test('searches todo and subtask titles case-insensitively and clears search', async ({ page }) => {
  const { cdp } = await seed(page)
  const search = page.getByPlaceholder('Search todos and subtasks...')
  await search.fill('MEETING')
  await expect(page.locator('.todo-row')).toHaveCount(1)
  await expect(page.locator('.todo-title')).toHaveText('Team meeting')
  await search.fill('MILK')
  await expect(page.locator('.todo-title')).toHaveText('Shopping')
  await page.getByRole('button', { name: 'Clear search' }).click()
  await expect(page.locator('.todo-row')).toHaveCount(2)
  await expect(page.getByRole('button', { name: 'Clear All', exact: true })).toHaveCount(0)
  await cdp.detach()
})

test('combines all criteria, counts matching sections, and resets every dimension', async ({ page }) => {
  const { cdp, meeting } = await seed(page)
  const date = toSingaporeDateTimeInput(meeting.due_date).slice(0, 10)
  await page.getByPlaceholder('Search todos and subtasks...').fill('meeting')
  await page.getByLabel('Filter by priority').selectOption('high')
  await page.getByLabel('Filter by tag').selectOption({ label: 'Work' })
  const advanced = page.getByRole('button', { name: /Advanced/ })
  await advanced.click()
  await expect(advanced).toHaveAttribute('aria-expanded', 'true')
  await page.getByLabel('Completion status').selectOption('incomplete')
  await page.getByLabel('Due Date From').fill(date)
  await page.getByLabel('Due Date To').fill(date)
  await expect(page.locator('.todo-title')).toHaveText('Team meeting')
  await expect(page.locator('.todo-section')).toHaveCount(1)
  await expect(page.locator('.todo-section-heading > span')).toHaveText('1')
  await page.getByLabel('Completion status').selectOption('completed')
  await expect(page.getByText('No todos match your filters')).toBeVisible()
  await expect(page.locator('.todo-section')).toHaveCount(0)
  await page.getByRole('button', { name: 'Clear All', exact: true }).click()
  await expect(page.locator('.todo-row')).toHaveCount(2)
  await expect(page.getByLabel('Filter by priority')).toHaveValue('all')
  await expect(page.getByLabel('Filter by tag')).toHaveValue('all')
  await expect(page.getByLabel('Completion status')).toHaveValue('all')
  await expect(page.getByLabel('Due Date From')).toHaveValue('')
  await expect(page.getByLabel('Due Date To')).toHaveValue('')
  await expect(page.getByPlaceholder('Search todos and subtasks...')).toHaveValue('')
  await advanced.click()
  await expect(page.getByLabel('Completion status')).toBeHidden()
  await cdp.detach()
})

test('priority, tag, completion and date filters work independently', async ({ page }) => {
  const { cdp, meeting } = await seed(page)
  await page.getByLabel('Filter by priority').selectOption('low')
  await expect(page.locator('.todo-title')).toHaveText('Shopping')
  await page.getByRole('button', { name: 'Clear All', exact: true }).click()
  await page.getByLabel('Filter by tag').selectOption({ label: 'Work' })
  await expect(page.locator('.todo-title')).toHaveText('Team meeting')
  await page.getByRole('button', { name: 'Clear All', exact: true }).click()
  await page.getByRole('button', { name: /Advanced/ }).click()
  await page.getByLabel('Completion status').selectOption('completed')
  await expect(page.locator('.todo-title')).toHaveText('Shopping')
  await page.getByRole('button', { name: 'Clear All', exact: true }).click()
  const date = toSingaporeDateTimeInput(meeting.due_date).slice(0, 10)
  await page.getByLabel('Due Date From').fill(date)
  await page.getByLabel('Due Date To').fill(date)
  await expect(page.locator('.todo-row')).toHaveCount(2)
  await page.getByLabel('Due Date From').fill('2100-01-01')
  await expect(page.getByText('From date is after To date')).toBeVisible()
  await expect(page.getByText('No todos match your filters')).toBeVisible()
  await cdp.detach()
})

test('saved presets survive reload, replace all dimensions, and delete after confirmation', async ({ page }) => {
  const { cdp, meeting } = await seed(page)
  const date = toSingaporeDateTimeInput(meeting.due_date).slice(0, 10)
  await page.getByPlaceholder('Search todos and subtasks...').fill('MEETING')
  await page.getByLabel('Filter by priority').selectOption('high')
  await page.getByLabel('Filter by tag').selectOption({ label: 'Work' })
  await page.getByRole('button', { name: /Advanced/ }).click()
  await page.getByLabel('Completion status').selectOption('incomplete')
  await page.getByLabel('Due Date From').fill(date)
  await page.getByLabel('Due Date To').fill(date)
  await page.getByRole('button', { name: 'Save Filter', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Save filter preset' })
  await expect(dialog).toContainText('Search: "MEETING"')
  await expect(dialog).toContainText('Priority: High')
  await expect(dialog).toContainText('Tag: Work')
  await expect(dialog).toContainText('Completion: Incomplete')
  await expect(dialog).toContainText(`Date: ${date} to ${date}`)
  await dialog.getByLabel('Preset name').fill('Morning focus')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.reload()
  await expect(page.locator('.todo-row')).toHaveCount(2)
  await page.getByRole('button', { name: /Advanced/ }).click()
  await page.getByLabel('Completion status').selectOption('completed')
  await page.getByRole('button', { name: 'Morning focus', exact: true }).click()
  await expect(page.locator('.todo-title')).toHaveText('Team meeting')
  await expect(page.getByPlaceholder('Search todos and subtasks...')).toHaveValue('MEETING')
  await expect(page.getByLabel('Filter by priority')).toHaveValue('high')
  await expect(page.getByLabel('Completion status')).toHaveValue('incomplete')
  await expect(page.getByLabel('Filter by tag').locator('option:checked')).toHaveText('Work')
  await expect(page.getByLabel('Due Date From')).toHaveValue(date)
  await expect(page.getByLabel('Due Date To')).toHaveValue(date)
  page.once('dialog', (confirmation) => confirmation.accept())
  await page.getByRole('button', { name: 'Delete preset Morning focus' }).click()
  await expect(page.getByRole('button', { name: 'Morning focus', exact: true })).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: /Advanced/ }).click()
  await expect(page.getByRole('button', { name: 'Morning focus', exact: true })).toHaveCount(0)
  await cdp.detach()
})

test('empty accounts, whitespace, corrupted storage and no matches degrade gracefully', async ({ page }) => {
  const cdp = await register(page)
  await expect(page.getByText('You have no todos yet')).toBeVisible()
  await expect(page.getByLabel('Filter by tag')).toHaveCount(0)
  await page.evaluate(() => localStorage.setItem('todo-app:filter-presets', '{broken'))
  await page.reload()
  await expect(page.getByText('You have no todos yet')).toBeVisible()
  await createTodo(page, 'First task')
  await expect(page.locator('.todo-row')).toHaveCount(1)
  await page.getByPlaceholder('Search todos and subtasks...').fill('   ')
  await expect(page.getByRole('button', { name: 'Clear All', exact: true })).toHaveCount(0)
  await page.getByPlaceholder('Search todos and subtasks...').fill('nothing matches')
  await expect(page.getByText('No todos match your filters')).toBeVisible()
  await expect(page.getByText('You have no todos yet')).toHaveCount(0)
  await cdp.detach()
})

test('save dialog is keyboard accessible and restores focus on Escape', async ({ page }) => {
  const { cdp } = await seed(page)
  await page.getByLabel('Filter by priority').selectOption('high')
  const save = page.getByRole('button', { name: 'Save Filter', exact: true })
  await save.click()
  const dialog = page.getByRole('dialog', { name: 'Save filter preset' })
  await expect(dialog.getByLabel('Preset name')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(save).toBeFocused()
  await cdp.detach()
})
